#!/usr/bin/env python3
"""Turn the honeypot's fake filesystem into the one the public page walks.

The page lets a visitor type `ls /root` and `cat /opt/app/.env` in a terminal
and answers with what the honeypot itself would have said. That claim is only
true while the two agree, so the page is not given a hand written copy: this
reads `config/filesystem.yaml`, the same file the daemon loads, and writes
`web/data/shell.json`.

A test regenerates it and compares, so a change to the fake filesystem that is
not carried over to the page fails the build rather than quietly making the
page a liar.

    python tools/shell_export.py --output web/data/shell.json
"""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
from typing import Any

import yaml

# The defaults in include/arapuca/ssh/vfs.hpp. A node that does not say.
DEFAULT_OWNER = "root"
DEFAULT_GROUP = "root"
DEFAULT_MTIME = "Nov  2 14:30"
DIR_MODE = "drwxr-xr-x"
FILE_MODE = "-rw-r--r--"

# The page is a web page, not a shell account: a single enormous decoy file
# would be paid for by every visitor on a phone. Nothing in the fake
# filesystem is near this today, and the figure is reported when it bites.
MAX_FILE_BYTES = 8192
TRUNCATION_NOTE = "\n... truncated for the web terminal ...\n"


def walk(node: dict[str, Any], path: str, out: dict[str, Any]) -> None:
    """Flatten the YAML tree into {absolute path: entry}."""
    is_dir = node.get("type") == "dir"
    entry: dict[str, Any] = {
        "dir": is_dir,
        "mode": node.get("mode") or (DIR_MODE if is_dir else FILE_MODE),
        "owner": node.get("owner") or DEFAULT_OWNER,
        "group": node.get("group") or DEFAULT_GROUP,
        "mtime": node.get("mtime") or DEFAULT_MTIME,
    }

    if is_dir:
        children = node.get("children") or {}
        entry["children"] = sorted(children.keys())
        out[path] = entry
        for name, child in children.items():
            separator = "" if path.endswith("/") else "/"
            walk(child, f"{path}{separator}{name}", out)
        return

    content = node.get("content") or ""
    if len(content.encode("utf-8")) > MAX_FILE_BYTES:
        content = content[:MAX_FILE_BYTES] + TRUNCATION_NOTE
    entry["content"] = content
    entry["size"] = len(content.encode("utf-8"))
    out[path] = entry


def build(tree: dict[str, Any]) -> dict[str, Any]:
    root = tree.get("root")
    if not isinstance(root, dict):
        raise SystemExit("filesystem.yaml has no 'root' mapping")

    out: dict[str, Any] = {}
    walk({"type": "dir", "children": root}, "/", out)
    return {
        "note": "Generated by tools/shell_export.py from config/filesystem.yaml. Do not edit.",
        "hostname": "srv-web-03",
        "files": out,
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", default="config/filesystem.yaml")
    parser.add_argument("--output", default="web/data/shell.json")
    arguments = parser.parse_args()

    source = pathlib.Path(arguments.source)
    tree = yaml.safe_load(source.read_text(encoding="utf-8"))
    payload = build(tree)

    path = pathlib.Path(arguments.output)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, indent=1, sort_keys=True) + "\n", encoding="utf-8")

    files = payload["files"]
    directories = sum(1 for entry in files.values() if entry["dir"])
    print(
        f"wrote {path}: {len(files)} paths, {directories} directories, "
        f"{len(files) - directories} files",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
